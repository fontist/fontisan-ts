#!/usr/bin/env bash
# Rebuild vendor/fontisan.wasm from fontist/fontisan-rs at the rev pinned in ENGINE_REV, then write
# vendor/BUILT_FROM.json and src/integrity.ts (the checksum the loader verifies against).
# The engine is consumed read-only: it is exported with `git archive` into a scratch dir.
# usage: scripts/refresh-wasm.sh            (clones https://github.com/fontist/fontisan-rs)
#        FONTISAN_RS_SRC=/path/to/fontisan-rs scripts/refresh-wasm.sh   (a local clone that has the rev)
# Needs: cargo + `rustup target add wasm32-unknown-unknown`, git, shasum.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
rev="$(tr -d '[:space:]' < "$here/ENGINE_REV")"
work="$(mktemp -d "${TMPDIR:-/tmp}/fontisan-ts-refresh.XXXXXX")"
trap 'rm -rf "$work"' EXIT
if [ -n "${FONTISAN_RS_SRC:-}" ]; then
  git -C "$FONTISAN_RS_SRC" archive --format=tar "$rev" | { mkdir "$work/src"; tar -x -C "$work/src"; }
else
  git clone --quiet --filter=blob:none --no-checkout https://github.com/fontist/fontisan-rs "$work/clone"
  git -C "$work/clone" archive --format=tar "$rev" | { mkdir "$work/src"; tar -x -C "$work/src"; }
fi
export CARGO_TARGET_DIR="$work/target"
export CARGO_PROFILE_RELEASE_OPT_LEVEL=s CARGO_PROFILE_RELEASE_LTO=true \
  CARGO_PROFILE_RELEASE_CODEGEN_UNITS=1 CARGO_PROFILE_RELEASE_STRIP=debuginfo
(cd "$work/src" && cargo build --release --locked --target wasm32-unknown-unknown -p fontisan-ffi)
mkdir -p "$here/vendor"
cp "$CARGO_TARGET_DIR/wasm32-unknown-unknown/release/fontisan.wasm" "$here/vendor/fontisan.wasm"
sha="$(shasum -a 256 "$here/vendor/fontisan.wasm" | cut -d' ' -f1)"
cat > "$here/vendor/BUILT_FROM.json" <<JSON
{
  "repository": "https://github.com/fontist/fontisan-rs",
  "engine_rev": "$rev",
  "target": "wasm32-unknown-unknown",
  "package": "fontisan-ffi",
  "rustc": "$(rustc --version)",
  "abi_version": 2,
  "files": { "fontisan.wasm": "$sha" }
}
JSON
cat > "$here/src/integrity.ts" <<TS
// Generated by scripts/refresh-wasm.sh; do not edit. Engine rev $rev.
export const ENGINE_REV = '$rev';
export const WASM_SHA256 = '$sha';
TS
echo "vendor/fontisan.wasm sha256=$sha engine=$rev"
